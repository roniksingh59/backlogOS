import express from 'express';
import path from 'path';
import fs from 'fs';
import cors from 'cors';
import dotenv from 'dotenv';
import { fileURLToPath } from 'url';
import { apiRouter } from './src/api.ts';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Load environment variables
dotenv.config();

// Also attempt loading .dev.env.json if present
try {
  const envFileCandidates = [
    path.resolve(process.cwd(), '.dev.env.json'),
    path.resolve(__dirname, '.dev.env.json'),
    path.resolve(process.cwd(), '../.dev.env.json'),
    '/app/.dev.env.json',
  ];
  for (const envFile of envFileCandidates) {
    if (fs.existsSync(envFile)) {
      const devEnv = JSON.parse(fs.readFileSync(envFile, 'utf-8'));
      for (const [key, val] of Object.entries(devEnv)) {
        if (!process.env[key] && typeof val === 'string') {
          process.env[key] = val;
        }
      }
      break;
    }
  }
} catch (e) {
  // Ignore non-fatal env load errors
}

// Global process error handlers to prevent Cloud Run container crashes
process.on('uncaughtException', (err) => {
  console.error('[BacklogOS] Uncaught exception:', err);
});
process.on('unhandledRejection', (reason, promise) => {
  console.error('[BacklogOS] Unhandled promise rejection at:', promise, 'reason:', reason);
});

const app = express();

app.use(cors());
app.use(express.json());

// Health check endpoints for Google Cloud Run, Kubernetes, and Nginx probes
app.all(['/healthz', '/health', '/_health'], (_req, res) => {
  res.status(200).send('OK');
});

// API routes
app.use('/api', apiRouter);

// Resolve static dist directory across varied deployment cwd environments
function resolveStaticDist(): string {
  const possiblePaths = [
    path.resolve(__dirname, 'dist'),
    path.resolve(process.cwd(), 'dist'),
    path.resolve(__dirname, 'artifacts/backlogos/dist'),
    path.resolve(process.cwd(), 'artifacts/backlogos/dist'),
    path.resolve(process.cwd(), '../artifacts/backlogos/dist'),
    '/app/applet/dist',
    '/app/applet/artifacts/backlogos/dist',
  ];

  for (const candidate of possiblePaths) {
    if (fs.existsSync(candidate) && fs.existsSync(path.join(candidate, 'index.html'))) {
      return candidate;
    }
    // Handle nested dist/dist if ever generated by recursive copy
    if (fs.existsSync(candidate) && fs.existsSync(path.join(candidate, 'dist', 'index.html'))) {
      return path.join(candidate, 'dist');
    }
  }

  // Fallback to first candidate
  return possiblePaths[0];
}

const staticDist = resolveStaticDist();
console.log(`[BacklogOS] Serving static frontend from: ${staticDist}`);

if (fs.existsSync(staticDist)) {
  app.use(express.static(staticDist));
}

// Fallback SPA handler compatible with Express 5
app.use((req, res) => {
  // If a static asset was requested but not found, return 404 instead of returning index.html
  if (req.path.startsWith('/assets/') || req.path.endsWith('.js') || req.path.endsWith('.css')) {
    res.status(404).send('Asset not found');
    return;
  }

  const indexHtml = path.join(staticDist, 'index.html');
  if (fs.existsSync(indexHtml)) {
    res.sendFile(indexHtml, (err) => {
      if (err && !res.headersSent) {
        res.status(500).send('Error loading BacklogOS interface.');
      }
    });
  } else {
    res.status(200).send('BacklogOS is running. Please run npm run build to compile the frontend.');
  }
});

// Cloud Run requires listening strictly on the port specified by PORT (default 8080)
const port = process.env.PORT ? parseInt(process.env.PORT, 10) : 8080;

let serverInstance: any = null;

function startServer(targetPort: number) {
  const srv = app.listen(targetPort, '0.0.0.0', () => {
    console.log(`[BacklogOS] Application successfully serving on http://0.0.0.0:${targetPort}`);
  });

  srv.on('error', (err: any) => {
    console.error(`[BacklogOS] Server error on port ${targetPort}:`, err?.code || err);
    if (err?.code === 'EADDRINUSE' && targetPort === 8080) {
      console.warn(`[BacklogOS] Port 8080 in use, attempting fallback to port 3000...`);
      startServer(3000);
    }
  });

  serverInstance = srv;
  return srv;
}

startServer(port);

// Graceful termination for Cloud Run scale down and updates
const handleShutdown = (signal: string) => {
  console.log(`[BacklogOS] Received ${signal}. Closing HTTP server gracefully...`);
  if (serverInstance) {
    serverInstance.close(() => {
      console.log('[BacklogOS] HTTP server closed cleanly.');
      process.exit(0);
    });
    setTimeout(() => {
      console.error('[BacklogOS] Shutdown timeout exceeded, exiting.');
      process.exit(0);
    }, 5000).unref();
  } else {
    process.exit(0);
  }
};

process.on('SIGTERM', () => handleShutdown('SIGTERM'));
process.on('SIGINT', () => handleShutdown('SIGINT'));


